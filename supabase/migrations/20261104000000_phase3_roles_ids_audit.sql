-- Application ID: TBF-<year>-<5 digits>, one counter per year (Pakistan time).
-- INSERT .. ON CONFLICT DO UPDATE locks the year's row, so simultaneous requests are
-- serialised and never get the same number. The UNIQUE constraint on app_id is a
-- second safety net. Old IDs (TBF-0001 style) are kept unchanged.
create table if not exists public.app_id_counter (
  year integer primary key,
  last_value integer not null default 0
);
create or replace function public.next_app_id() returns text
  language plpgsql security definer set search_path = public as
$$ declare
  y integer := extract(year from (now() at time zone 'Asia/Karachi'))::integer;
  n integer;
  candidate text;
begin
  loop
    insert into public.app_id_counter (year, last_value) values (y, 1)
      on conflict (year) do update set last_value = public.app_id_counter.last_value + 1
      returning last_value into n;
    candidate := format('TBF-%s-%s', y, lpad(n::text, 5, '0'));
    exit when not exists (select 1 from public.application where app_id = candidate);
  end loop;
  return candidate;
end $$;
alter table public.application alter column app_id set default public.next_app_id();

create or replace function public.tg_app_id_immutable() returns trigger
  language plpgsql set search_path = public as
$$ begin
  if old.app_id is not null and new.app_id is distinct from old.app_id then
    raise exception 'Application ID cannot be changed' using errcode = '42501';
  end if;
  return new;
end $$;
drop trigger if exists app_id_immutable on public.application;
create trigger app_id_immutable before update of app_id on public.application
  for each row execute function public.tg_app_id_immutable();

-- Duplicate-CNIC warning: returns only ID/status/date of other applications with the
-- same CNIC, so staff are warned even about applications they are not allowed to open.
create or replace function public.cnic_matches(p_cnic text, p_exclude bigint)
  returns table (app_id varchar, status varchar, created_at timestamp)
  language sql stable security definer set search_path = public as
$$ select a.app_id, a.status, a.created_at from public.application a
   where p_cnic <> '' and a.cnic = p_cnic and a.id <> coalesce(p_exclude, -1)
     and a.deleted_at is null
   order by a.id $$;

