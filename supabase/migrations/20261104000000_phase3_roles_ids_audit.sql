create or replace function public.tg_status_guard() returns trigger
  language plpgsql set search_path = public as
$$ begin
  if new.status is distinct from old.status and public.app_role() not in ('Admin', 'system', 'legacy') then
    if not exists (select 1 from public.status_transition t
                   where t.from_status = old.status and t.to_status = new.status
                     and public.app_can(t.permission)) then
      raise exception 'Status change % -> % not allowed', old.status, new.status
        using errcode = '42501';
    end if;
  end if;
  if new.status = 'Rejected' and new.status is distinct from old.status
     and coalesce(btrim(new.rejection_reason), '') = '' then
    raise exception 'A rejection reason is required' using errcode = '23514';
  end if;
  return new;
end $$;
drop trigger if exists status_guard on public.application;
create trigger status_guard before update of status on public.application
  for each row execute function public.tg_status_guard();

