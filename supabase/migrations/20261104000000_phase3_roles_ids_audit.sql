create or replace function public.app_can(p text) returns boolean
  language sql stable security definer set search_path = public as
$$ select public.app_role() in ('Admin', 'system', 'legacy')
       or exists (select 1 from public.role_permission rp
                  where rp.role = public.app_role() and rp.permission = p) $$;

-- Non-admins may change their own password, but never their own role/username/active flag.
create or replace function public.tg_user_guard() returns trigger
  language plpgsql set search_path = public as
$$ begin
  if not public.app_can('users.manage') and (new.role is distinct from old.role
       or new.username is distinct from old.username or new.active is distinct from old.active
       or new.deleted_at is distinct from old.deleted_at) then
    raise exception 'Not allowed to change user role/status' using errcode = '42501';
  end if;
  return new;
end $$;
drop trigger if exists user_guard on public."user";
create trigger user_guard before update on public."user"
  for each row execute function public.tg_user_guard();

