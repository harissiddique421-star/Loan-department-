-- ------------------------------------------------------------------ disbursement sheets
create table if not exists public.disbursement_batch (
  id bigint generated by default as identity primary key,
  number integer not null unique check (number > 0),
  disb_date date not null,
  month smallint not null check (month between 1 and 12),
  year smallint not null check (year between 2000 and 2200),
  status varchar(10) not null default 'open' check (status in ('open', 'closed')),
  notes text,
  created_by bigint references public."user"(id),
  created_at timestamp not null default now(),
  closed_by bigint references public."user"(id),
  closed_at timestamp,
  reopened_by bigint references public."user"(id),
  reopened_at timestamp,
  reopen_reason text
);
create index if not exists disbursement_batch_period_idx on public.disbursement_batch(year, month);

create table if not exists public.disbursement_entry (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.disbursement_batch(id),
  application_id bigint not null references public.application(id),
  -- values as they were when added (the printed sheet must not change later)
  name varchar(200),
  cnic varchar(30),
  phone varchar(30),
  amount numeric(12, 2),
  purpose varchar(80),
  loan_number varchar(30),
  fee_amount numeric(12, 2),
  added_by bigint references public."user"(id),
  added_at timestamp not null default now(),
  disbursed_at timestamp,
  disbursed_by bigint references public."user"(id),
  removed_at timestamp,
  removed_by bigint references public."user"(id),
  remove_reason text
);
-- one active row per application, across all sheets: no duplicates
create unique index if not exists disbursement_entry_app_uniq
  on public.disbursement_entry(application_id) where removed_at is null;
create index if not exists disbursement_entry_batch_idx on public.disbursement_entry(batch_id);

create table if not exists public.cheque (
  id bigint generated by default as identity primary key,
  entry_id bigint not null references public.disbursement_entry(id),
  cheque_no varchar(40) not null check (btrim(cheque_no) <> ''),
  status varchar(12) not null default 'Issued'
    check (status in ('Pending', 'Issued', 'Cleared', 'Cancelled')),
  cancel_reason text,
  created_by bigint references public."user"(id),
  created_at timestamp not null default now(),
  updated_by bigint references public."user"(id),
  updated_at timestamp,
  cancelled_by bigint references public."user"(id),
  cancelled_at timestamp
);
-- a cheque number can be active only once; cancelled cheques stay as history
create unique index if not exists cheque_active_no_uniq on public.cheque(cheque_no) where status <> 'Cancelled';
create unique index if not exists cheque_one_active_per_entry on public.cheque(entry_id) where status <> 'Cancelled';
create index if not exists cheque_entry_idx on public.cheque(entry_id);

-- Closed sheets are read-only; reopening needs period.close and a reason.
create or replace function public.tg_batch_guard() returns trigger
  language plpgsql set search_path = public as
$$ begin
  if old.status = 'closed' and new.status = 'closed' then
    raise exception 'Disbursement sheet % is closed', old.number using errcode = '42501';
  end if;
  if old.status <> new.status then
    if not public.app_can('period.close') then
      raise exception 'Not allowed to close or reopen' using errcode = '42501';
    end if;
    if new.status = 'open' and coalesce(btrim(new.reopen_reason), '') = '' then
      raise exception 'A reason is required to reopen' using errcode = '23514';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists batch_guard on public.disbursement_batch;
create trigger batch_guard before update on public.disbursement_batch
  for each row execute function public.tg_batch_guard();

create or replace function public.tg_entry_open_batch() returns trigger
  language plpgsql set search_path = public as
$$ declare b bigint; begin
  b := coalesce(new.batch_id, old.batch_id);
  if (select status from public.disbursement_batch where id = b) = 'closed' then
    raise exception 'Disbursement sheet is closed' using errcode = '42501';
  end if;
  return coalesce(new, old);
end $$;
drop trigger if exists entry_open_batch on public.disbursement_entry;
create trigger entry_open_batch before insert or update or delete on public.disbursement_entry
  for each row execute function public.tg_entry_open_batch();

create or replace function public.tg_cheque_open_batch() returns trigger
  language plpgsql set search_path = public as
$$ declare e bigint; begin
  e := coalesce(new.entry_id, old.entry_id);
  if (select b.status from public.disbursement_entry x join public.disbursement_batch b on b.id = x.batch_id
      where x.id = e) = 'closed' then
    raise exception 'Disbursement sheet is closed' using errcode = '42501';
  end if;
  if tg_op = 'DELETE' then
    raise exception 'Cheques are never deleted; cancel them instead' using errcode = '42501';
  end if;
  if tg_op = 'UPDATE' and old.status = 'Cancelled' then
    raise exception 'A cancelled cheque cannot be changed' using errcode = '42501';
  end if;
  if new.status = 'Cancelled' and coalesce(btrim(new.cancel_reason), '') = '' then
    raise exception 'A reason is required to cancel a cheque' using errcode = '23514';
  end if;
  return new;
end $$;
drop trigger if exists cheque_open_batch on public.cheque;
create trigger cheque_open_batch before insert or update or delete on public.cheque
  for each row execute function public.tg_cheque_open_batch();

-- ------------------------------------------------------------------ Google Sheets sync state
create table if not exists public.gsheet_year (
  year smallint primary key,
  spreadsheet_id varchar(100),
  url text,
  tab_ids jsonb,
  status varchar(10) not null default 'creating' check (status in ('creating', 'ready', 'failed')),
  created_at timestamp not null default now()
);
create table if not exists public.gsheet_sync (
  year smallint not null,
  month smallint not null check (month between 0 and 12),     -- 0 = Yearly Summary
  dirty boolean not null default true,
  attempts integer not null default 0,
  last_error text,
  requested_at timestamp not null default now(),
  synced_at timestamp,
  primary key (year, month)
);
create table if not exists public.gsheet_sync_log (
  id bigint generated by default as identity primary key,
  year smallint,
  month smallint,
  ok boolean not null,
  message text,
  created_at timestamp not null default now()
);

