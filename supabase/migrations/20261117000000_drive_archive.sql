-- =====================================================================================
-- Google Drive archive: bookkeeping for the Word-form archive and the database backups.
--
-- SAFE TO RE-RUN. Additive only: three NEW tables; no existing table, column or row is
-- touched. Until this runs, the website works exactly as before and the archive stays off.
--
--   archive_file    every file the app put (or tried to put) in Drive, with its md5 and status
--   archive_run     backup / verification history (Admin → Backup & Recovery)
--   archive_setting Drive folder ids and the encrypted Google Drive sign-in token
--
-- Only Admin (and the nightly job, role 'system') can read or write them. The Drive token is
-- encrypted by the app with SECRET_KEY before it is stored.
--
-- ROLLBACK (removes only the bookkeeping, never application data, never Drive files):
--   drop table public.archive_file, public.archive_run, public.archive_setting;
-- =====================================================================================
begin;

create table if not exists public.archive_file (
  id bigint generated by default as identity primary key,
  application_id bigint,                  -- no foreign key on purpose: never blocks app changes
  document_id bigint,
  category varchar(20) not null,          -- form | version | guarantor | document | database | report
  version integer,
  name varchar(300) not null,
  drive_file_id varchar(100),
  drive_folder_id varchar(100),
  md5 varchar(32),
  size bigint,
  fingerprint varchar(200),
  status varchar(12) not null default 'pending',
  attempts integer not null default 0,
  last_error text,
  created_at timestamp not null default now(),
  uploaded_at timestamp,
  verified_at timestamp
);
create index if not exists archive_file_app_idx on public.archive_file (application_id, category, version);
create index if not exists archive_file_status_idx on public.archive_file (status);

create table if not exists public.archive_run (
  id bigint generated by default as identity primary key,
  kind varchar(20) not null,
  started_at timestamp not null default now(),
  finished_at timestamp,
  ok boolean,
  message text,
  summary jsonb
);

create table if not exists public.archive_setting (
  key varchar(60) primary key,
  value text,
  updated_at timestamp default now()
);

revoke all on public.archive_file, public.archive_run, public.archive_setting from anon, authenticated;
grant select, insert, update on public.archive_file, public.archive_run, public.archive_setting to tooba_app;
grant usage, select on all sequences in schema public to tooba_app;

alter table public.archive_file enable row level security;
alter table public.archive_run enable row level security;
alter table public.archive_setting enable row level security;

drop policy if exists archive_file_all on public.archive_file;
create policy archive_file_all on public.archive_file for all to tooba_app
  using ((select public.app_can('export'))) with check ((select public.app_can('export')));
drop policy if exists archive_run_all on public.archive_run;
create policy archive_run_all on public.archive_run for all to tooba_app
  using ((select public.app_can('export'))) with check ((select public.app_can('export')));
drop policy if exists archive_setting_all on public.archive_setting;
create policy archive_setting_all on public.archive_setting for all to tooba_app
  using ((select public.app_can('export'))) with check ((select public.app_can('export')));

commit;
