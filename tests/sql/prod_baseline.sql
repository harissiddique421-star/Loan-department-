-- Tooba Foundation database setup for Supabase PostgreSQL
-- Run in Supabase SQL Editor. Keep applicant data private.
create table if not exists public."user" (
  id bigint generated by default as identity primary key,
  username varchar(80) unique not null,
  password_hash varchar(255) not null,
  role varchar(20) default 'Staff',
  active boolean default true
);
create table if not exists public.application (
  id bigint generated by default as identity primary key,
  app_id varchar(20) unique,
  applicant_name varchar(200) default '',
  cnic varchar(30),
  status varchar(30) default 'Draft',
  assigned_to bigint references public."user"(id),
  form_json text default '{}',
  created_by bigint references public."user"(id),
  updated_by bigint references public."user"(id),
  created_at timestamp,
  updated_at timestamp
);
create index if not exists application_app_id_idx on public.application(app_id);
create index if not exists application_cnic_idx on public.application(cnic);
create table if not exists public.document (
  id bigint generated by default as identity primary key,
  application_id bigint references public.application(id) not null,
  original_name varchar(255),
  stored_name varchar(255) unique,
  kind varchar(20) default 'document',
  content_type varchar(120) default 'application/octet-stream',
  size integer default 0,
  storage varchar(20) default 'db',
  data bytea,
  uploaded_by bigint references public."user"(id),
  created_at timestamp
);
create table if not exists public.log (
  id bigint generated by default as identity primary key,
  user_id bigint references public."user"(id),
  action varchar(200),
  application_id bigint,
  created_at timestamp
);
-- The app adds any missing columns automatically on startup, so running this file is optional.
-- The Flask server connects with the database password; keep the browser away from these tables:
alter table public."user" enable row level security;
alter table public.application enable row level security;
alter table public.document enable row level security;
alter table public.log enable row level security;
-- Reproduces production migrations 20261102142828 (loan_form_photos_and_audit) and
-- 20261102144341 (tooba_app_role) with a TEST-ONLY password.
alter table public.application add column if not exists updated_by bigint references public."user"(id);
alter table public.document add column if not exists kind varchar(20) default 'document';
alter table public.document add column if not exists content_type varchar(120) default 'application/octet-stream';
alter table public.document add column if not exists size integer default 0;
alter table public.document add column if not exists storage varchar(20) default 'db';
alter table public.document add column if not exists data bytea;
create index if not exists document_application_id_idx on public.document(application_id);
create index if not exists log_application_id_idx on public.log(application_id);
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'tooba_app') then
    create role tooba_app login password 'test-only';
  end if;
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
end $$;
grant usage on schema public to tooba_app;
grant select, insert, update, delete on public."user", public.application, public.document, public.log to tooba_app;
grant usage, select on all sequences in schema public to tooba_app;
grant all on all tables in schema public to anon, authenticated;
drop policy if exists tooba_app_all on public."user";
create policy tooba_app_all on public."user" for all to tooba_app using (true) with check (true);
drop policy if exists tooba_app_all on public.application;
create policy tooba_app_all on public.application for all to tooba_app using (true) with check (true);
drop policy if exists tooba_app_all on public.document;
create policy tooba_app_all on public.document for all to tooba_app using (true) with check (true);
drop policy if exists tooba_app_all on public.log;
create policy tooba_app_all on public.log for all to tooba_app using (true) with check (true);
